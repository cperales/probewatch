#!/usr/bin/env python3
"""Export the Ghidra symbol map from JSON to Ghidra-importable formats.

Reads ``secrets/ghidra/symbols.json`` (the single source of truth for both
HCPU and LCPU images) and writes:

- ``secrets/ghidra/symbols.ghidra.txt`` — ``ImportSymbolsScript.py`` format
  (one line per symbol: ``name addr f``), only rows with
  ``confidence != low`` and a non-null ``entry``.
- ``secrets/ghidra/apply_symbols.py`` — a Python script that can be run
  against a REA session to replay the symbol map (entry -> name) for every
  symbol that has a non-null ``entry``.

Usage:
    uv run python scripts/export_symbols.py [--dry-run]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYMBOLS_JSON = ROOT / "secrets" / "ghidra" / "symbols.json"
TXT_OUT = ROOT / "secrets" / "ghidra" / "symbols.ghidra.txt"
APPLY_OUT = ROOT / "scripts" / "apply_symbols.py"


def load_symbols(path: Path) -> dict:
    """Load the merged symbols JSON."""
    with path.open() as f:
        return json.load(f)


def filter_symbols(symbols: list[dict]) -> list[dict]:
    """Return only symbols with confidence != low and a non-null entry."""
    return [s for s in symbols if s.get("confidence") != "low" and s.get("entry") is not None]


def export_txt(data: dict, path: Path, dry_run: bool = False) -> int:
    """Write symbols.ghidra.txt in ImportSymbolsScript.py format.

    Format: ``name addr f`` (addr is hex with 0x prefix).
    Only symbols with confidence != low and non-null entry.
    """
    lines: list[str] = []

    # Write metadata comments
    lines.append("# Auto-generated by export_symbols.py — do not edit")
    lines.append(f"# Source: {SYMBOLS_JSON.name}")
    lines.append("")

    # Group by image
    images = data.get("images", {})
    for img_key in ("hcpu", "lcpu"):
        img = images.get(img_key)
        if not img:
            continue
        lines.append(f"# --- {img_key.upper()} ---")
        lines.append(f"# {img.get('image', img_key)}")
        lines.append(f"# load_base: {img.get('load_base', 'unknown')}")
        lines.append("")

        symbols = img.get("symbols", [])
        filtered = filter_symbols(symbols)
        for s in filtered:
            entry = s["entry"]
            # Convert entry to int if it's a hex string
            entry_int = int(entry, 16) if isinstance(entry, str) else entry
            lines.append(f"{s['name']} 0x{entry_int:x} f")

        lines.append("")

    # Also handle legacy top-level symbols array (backward compat)
    if "symbols" in data and isinstance(data["symbols"], list):
        lines.append("# --- legacy top-level symbols ---")
        filtered = filter_symbols(data["symbols"])
        for s in filtered:
            entry = s["entry"]
            entry_int = int(entry, 16) if isinstance(entry, str) else entry
            lines.append(f"{s['name']} 0x{entry_int:x} f")
        lines.append("")

    content = "\n".join(lines) + "\n"

    if dry_run:
        print(f"[dry-run] would write {len(lines)} lines to {path}")
        return 0

    path.write_text(content)
    print(f"Wrote {len(lines)} lines to {path}")
    return 0


def export_apply(data: dict, path: Path, dry_run: bool = False) -> int:
    """Write apply_symbols.py — a Python script that replays the symbol map.

    The generated script reads the JSON and prints REA-compatible commands:
    ``set_address_name(image, addr, name)`` for each symbol with a non-null entry.
    """
    script_lines: list[str] = [
        "#!/usr/bin/env python3",
        '"""Apply the Ghidra symbol map to a REA session.',
        "",
        "Reads ``secrets/ghidra/symbols.json`` and prints",
        "``set_address_name(image, addr, name)`` commands for",
        "every symbol with a non-null entry.",
        "",
        "Usage:",
        "    uv run python scripts/apply_symbols.py",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import json",
        "import sys",
        "from pathlib import Path",
        "",
        "ROOT = Path(__file__).resolve().parent.parent",
        'SYMBOLS_JSON = ROOT / "secrets" / "ghidra" / "symbols.json"',
        "",
        "",
        "def load_symbols(path: Path) -> dict:",
        "    with path.open() as f:",
        "        return json.load(f)",
        "",
        "",
        "def apply(data: dict) -> None:",
        '    """Print set_address_name commands for each symbol."""',
        '    images = data.get("images", {})',
        '    for img_key in ("hcpu", "lcpu"):',
        "        img = images.get(img_key)",
        "        if not img:",
        "            continue",
        '        symbols = img.get("symbols", [])',
        "        for s in symbols:",
        '            entry = s.get("entry")',
        "            if entry is None:",
        "                continue",
        "            # Convert hex string to int",
        "            if isinstance(entry, str):",
        "                addr = int(entry, 16)",
        "            else:",
        "                addr = entry",
        "            print(f\"set_address_name({img_key!r}, 0x{addr:x}, {s['name']!r})\")",
        "",
        "",
        'if __name__ == "__main__":',
        "    data = load_symbols(SYMBOLS_JSON)",
        "    apply(data)",
        "",
    ]

    content = "\n".join(script_lines) + "\n"

    if dry_run:
        print(f"[dry-run] would write {len(script_lines)} lines to {path}")
        return 0

    path.write_text(content)
    print(f"Wrote {len(script_lines)} lines to {path}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be written without touching files",
    )
    args = parser.parse_args()

    data = load_symbols(SYMBOLS_JSON)
    print(f"Loaded {SYMBOLS_JSON.name}")

    # Show structure
    if "images" in data:
        for key, img in data["images"].items():
            sym_count = len(img.get("symbols", []))
            print(f"  {key}: {sym_count} symbols")
    elif "symbols" in data:
        print(f"  top-level: {len(data['symbols'])} symbols")

    rc = 0
    rc |= export_txt(data, TXT_OUT, dry_run=args.dry_run)
    rc |= export_apply(data, APPLY_OUT, dry_run=args.dry_run)

    return rc


if __name__ == "__main__":
    sys.exit(main())
